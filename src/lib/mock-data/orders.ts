interface OrderSeedInput {
  id: string;
  folio: string;
  status: OrderStatus;
  customerId: string;
  bladeTypeId: string;
  serviceId: string;
  quotedPrice: number;
  requiresInvoice: boolean;
  createdAt: string;
  estimatedDelivery: string;
  droppedOffBy: string;
  receivedById: string;
  advancePaidAt?: string;
  deliveredAt?: string;
  pickedUpBy?: string;
  pickedUpPhone?: string;
  invoiceStatus?: Order["invoiceStatus"];
  notes?: string;
  updatedById?: string;
}

function makeOrder(input: OrderSeedInput): Order {
  const amounts = computeOrderAmounts(input.quotedPrice, input.requiresInvoice);
  const advancePaid = Boolean(input.advancePaidAt);
  return {
    id: input.id,
    folio: input.folio,
    status: input.status,
    customerId: input.customerId,
    bladeTypeId: input.bladeTypeId,
    serviceId: input.serviceId,
    quotedPrice: input.quotedPrice,
    ...amounts,
    advancePaid,
    advancePaidAt: input.advancePaidAt ?? null,
    estimatedDelivery: input.estimatedDelivery,
    deliveredAt: input.deliveredAt ?? null,
    droppedOffBy: input.droppedOffBy,
    pickedUpBy: input.pickedUpBy ?? null,
    pickedUpPhone: input.pickedUpPhone ?? null,
    receivedById: input.receivedById,
    updatedById: input.updatedById ?? null,
    requiresInvoice: input.requiresInvoice,
    invoiceStatus:
      input.invoiceStatus ?? (input.requiresInvoice ? "PENDING" : "NOT_REQUIRED"),
    notes: input.notes ?? null,
    createdAt: input.createdAt,
    updatedAt: input.deliveredAt ?? input.advancePaidAt ?? input.createdAt,
  };
}

