function makeOrderProduct(
  id: string,
  orderId: string,
  productId: string,
  quantity: number,
  unitPrice: number,
  status: ReglasStatus,
): OrderProduct {
  return {
    id,
    orderId,
    productId,
    quantity,
    unitPrice,
    subtotal: quantity * unitPrice,
    status,
  };
}

